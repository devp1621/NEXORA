// Builds a plain-text (Markdown) report from the analysis the server already calculated. Nothing is invented here.
const list = (items, fmt) => (items && items.length ? items.map(fmt).join("\n") : "_None._");

export function buildReport(profile, data) {
  const cov = data.careerSkillCoverage;
  const date = new Date().toLocaleDateString(undefined, { year: "numeric", month: "long", day: "numeric" });
  const gaps = [...(data.missingSkills || []), ...(data.inProgressSkills || [])].sort((a, b) => (a.suggestedOrder || 0) - (b.suggestedOrder || 0));
  return [
    `# Nexora career report: ${profile.name || "Student"}`,
    `Career compared: **${data.selectedCareer.title}** · ${date}`,
    "",
    `## Career Skill Coverage: ${cov.percent}%`,
    `${cov.matched} of ${cov.total} required skills matched, ${cov.inProgress} in progress, ${cov.missing} missing.`,
    `Proficiency depth (separate, not part of the score): ${data.proficiencyDepth.percent}%.`,
    "",
    `> ${data.scoring.disclaimer}`,
    "",
    "## Strengths",
    list(data.strengths, (s) => `- **${s.title}**: ${s.detail}`),
    "",
    "## Matched skills",
    list(data.matchedSkills, (s) => `- ${s.name}`),
    "",
    "## Priority improvement areas",
    list(data.priorityGaps, (g, i) => `${i + 1}. **${g.name}** (${g.priority}): ${g.why}`),
    "",
    "## All gaps, in suggested learning order",
    list(gaps, (g) => `- ${g.name}${g.status ? ` (${g.status})` : ""}`),
    "",
    "---",
    "Generated by Nexora. The score shows overlap with an illustrative skill list. It is not a prediction of hiring outcomes.",
    "",
  ].join("\n");
}

export function downloadText(filename, text) {
  const url = URL.createObjectURL(new Blob([text], { type: "text/markdown;charset=utf-8" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
